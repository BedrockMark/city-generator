"""People statistics from work/characters/detect/*.json + scenes.

For every detected outfit (= one person): pose, ground under foot, nearest objects (class) within 28px,
group size (other people within 24px), and which reference (theme) it occurs in.
Accessories are attached to the person whose outfit box overlaps them.
Writes work/characters/people.json and work/characters/people_summary.md
"""
import json
import numpy as np
from collections import Counter, defaultdict
from common import *

NEAR, GROUP = 28, 24
cat = {r['id']: r for r in json.load(open(WORK/'catalog.json'))}

def group_of(name):
    n = name.replace('Outfit_', '')
    return 'kid' if 'kid' in name else n.split('_')[0]

def main():
    people, byref = [], {}
    for n in ref_names():
        p = WORK/'characters'/'detect'/f'{n}.json'
        sp = WORK/'scenes'/f'{n}.json'
        if not p.exists() or not sp.exists(): continue
        dets = json.load(open(p)); sc = json.load(open(sp))
        outs = [d for d in dets if d['pack'] != 'Accessories']
        accs = [d for d in dets if d['pack'] == 'Accessories']
        objs = [o for o in sc['objects'] if o.get('conf') == 'high' and o['cls'] != 'building']
        ox, oy = sc['phase']; cx0, cy0 = sc['origin']
        G = sc['ground']
        rows = []
        for d in outs:
            fx, fy = d['x'] + 8, d['y'] + 31
            acc = [a['name'] for a in accs if abs(a['x'] - d['x']) <= 4 and abs(a['y'] - d['y']) <= 6]
            near = []
            for o in objs:
                bx0, by0, bx1, by1 = cat[o['sid']]['bbox']
                X0, Y0, X1, Y1 = o['x'] + bx0, o['y'] + by0, o['x'] + bx1, o['y'] + by1
                dx = max(X0 - fx, 0, fx - X1); dy = max(Y0 - fy, 0, fy - Y1)
                if np.hypot(dx, dy) <= NEAR: near.append(o['cls'] + ':' + o['name'])
            r, c = int((fy - oy) // T - cy0), int((fx - ox) // T - cx0)
            g = G[r][c] if 0 <= r < len(G) and 0 <= c < len(G[0]) else ''
            rows.append(dict(ref=n, kind=META[n]['kind'], outfit=d['name'], group=group_of(d['name']), pose=d['pose'],
                             x=fx, y=fy, ground=g, accessories=acc, near=near))
        for i, a in enumerate(rows):
            a['group_size'] = 1 + sum(1 for j, b in enumerate(rows) if j != i and np.hypot(a['x'] - b['x'], a['y'] - b['y']) < GROUP)
        people += rows; byref[n] = len(rows)
    json.dump(people, open(WORK/'characters'/'people.json', 'w'), indent=0)
    L = ['# People in references (auto-generated by tools/char_stats.py)', '',
         f'{len(people)} people detected in {sum(1 for v in byref.values() if v)} refs.', '',
         '## Per reference', '', '| ref | people | outfit groups | poses |', '|---|---|---|---|']
    for n in byref:
        ps = [p for p in people if p['ref'] == n]
        if not ps: continue
        L.append(f"| {n} | {len(ps)} | " + ', '.join(f'{g}:{k}' for g, k in Counter(p['group'] for p in ps).most_common()) +
                 ' | ' + ', '.join(f'{g}:{k}' for g, k in Counter(p['pose'] for p in ps).most_common()) + ' |')
    L += ['', '## Per outfit group: where it appears', '', '| group | n | refs | accessories | poses |', '|---|---|---|---|---|']
    bg = defaultdict(list)
    for p in people: bg[p['group']].append(p)
    for g, ps in sorted(bg.items(), key=lambda kv: -len(kv[1])):
        L.append(f"| {g} | {len(ps)} | " + ', '.join(f'{r}:{k}' for r, k in Counter(p['ref'] for p in ps).most_common(6)) +
                 ' | ' + ', '.join(f'{a}:{k}' for a, k in Counter(a for p in ps for a in p['accessories']).most_common(3)) +
                 ' | ' + ', '.join(f'{a}:{k}' for a, k in Counter(p['pose'] for p in ps).most_common(3)) + ' |')
    L += ['', '## Pose vs. nearby object class (within 28px of the foot)', '', '| pose | n | nearby classes |', '|---|---|---|']
    bp = defaultdict(list)
    for p in people: bp[p['pose']].append(p)
    for k, ps in bp.items():
        L.append(f"| {k} | {len(ps)} | " + ', '.join(f'{c}:{v}' for c, v in Counter(x.split(':')[0] for p in ps for x in p['near']).most_common(8)) + ' |')
    L += ['', '## Group size distribution', '', str(dict(sorted(Counter(p['group_size'] for p in people).items()))),
          '', '## Ground under people', '', str(dict(Counter(p['ground'] for p in people).most_common()))]
    open(WORK/'characters'/'people_summary.md', 'w', encoding='utf-8').write('\n'.join(L))
    print('\n'.join(L))

if __name__ == '__main__':
    main()
